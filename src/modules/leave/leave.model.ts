import type { LeaveType, LeaveStatus } from '../../shared/types';

/**
 * A single application by an employee for a period of leave of a given type,
 * subject to manager approval.
 *
 * A request is created as PENDING immediately (there is no DRAFT/SUBMITTED
 * state). `approvedBy` and `approvedAt` are null until the request is approved
 * or rejected and remain null for PENDING/CANCELLED. Lifecycle:
 * PENDING -> (APPROVED | REJECTED); PENDING -> CANCELLED (owner only);
 * APPROVED/REJECTED/CANCELLED are terminal. The repository persists status
 * transitions but does not enforce their legality (the service owns that).
 *
 * `id`, `status`, `approvedBy`, `approvedAt`, `createdAt` and `updatedAt` are
 * generated by the repository and never caller-supplied on create.
 */
export interface LeaveRequest {
  id: string;
  employeeId: string;
  leaveType: LeaveType;
  startDate: Date;
  endDate: Date;
  reason: string | undefined;
  status: LeaveStatus;
  approvedBy: string | null;
  approvedAt: Date | null;
  createdAt: Date;
  updatedAt: Date;
}
